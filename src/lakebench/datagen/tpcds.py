from ._tpcgen import TpcgenDataGenerator, _interpolate


class TPCDSDataGenerator(TpcgenDataGenerator):
    """
    Generate TPC-DS data with ``tpcgen-cli`` (installed by ``lakebench[tpcds_datagen]``).

    Parameters
    ----------
    scale_factor : float
        Scale factor that determines the generated dataset size.
    target_folder_uri : str
        Local or mounted folder. Each table is written to its own subfolder.
    target_row_group_size_mb : int, default=128
        Approximate uncompressed Parquet row-group size, passed to ``--row-group-bytes``.
    compression : str, default="ZSTD(1)"
        Parquet compression codec, for example ``"SNAPPY"`` or ``"ZSTD(3)"``.
    table_list : list of str, optional
        TPC-DS tables to generate. All 24 tables are generated by default.
    num_threads : int, optional
        Generator thread count. Defaults to all available CPU cores. Use a lower
        value such as 8 or 16 for large generations targeting mounted filesystems.
    output_format : {"parquet", "native"}, default="parquet"
        ``"native"`` writes the pipe-delimited ``.dat`` format of ``dsdgen``
        (preview). ``target_row_group_size_mb`` and ``compression`` apply only
        to Parquet.
    """

    BENCHMARK = "tpcds"
    NATIVE_FORMAT = "dat"
    SF10_SIZE_MIB = {
        "call_center": 0.0,
        "catalog_page": 0.5,
        "catalog_returns": 76.8,
        "catalog_sales": 794.7,
        "customer": 20.0,
        "customer_address": 3.8,
        "customer_demographics": 5.5,
        "date_dim": 1.6,
        "household_demographics": 0.0,
        "income_band": 0.0,
        "inventory": 418.6,
        "item": 6.5,
        "promotion": 0.0,
        "reason": 0.0,
        "ship_mode": 0.0,
        "store": 0.0,
        "store_returns": 115.7,
        "store_sales": 972.7,
        "time_dim": 0.9,
        "warehouse": 0.0,
        "web_page": 0.0,
        "web_returns": 40.7,
        "web_sales": 362.5,
        "web_site": 0.0,
    }
    #: TPC-DS row counts at the spec's defined scale factors for the tables that do not
    #: grow linearly and can exceed one million rows. Other tables grow linearly, or stay
    #: under one million rows, which tpcgen-cli never splits.
    DEFINED_SCALE_FACTORS = (1, 10, 100, 300, 1000, 3000, 10000, 30000, 100000)
    NONLINEAR_ROW_COUNTS = {
        "customer": (100000, 500000, 2000000, 5000000, 12000000, 30000000, 65000000, 80000000, 100000000),
        "customer_address": (50000, 250000, 1000000, 2500000, 6000000, 15000000, 32500000, 40000000, 50000000),
        "customer_demographics": (1920800,) * 9,
        "inventory": (
            11745000,
            133110000,
            399330000,
            585684000,
            783000000,
            1033560000,
            1311525000,
            1627857000,
            1965337830,
        ),
    }

    def _growth(self, table: str) -> float:
        rows = self.NONLINEAR_ROW_COUNTS.get(table)
        if rows is None:
            return super()._growth(table)
        return _interpolate(self.scale_factor, self.DEFINED_SCALE_FACTORS, rows) / rows[1]
